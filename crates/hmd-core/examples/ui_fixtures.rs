//! Writes the catalog texts the UI prototype shows (spec 011) as a TypeScript module, so the
//! prototype never drifts from the reviewed catalog:
//!
//! `cargo run -q -p hmd-core --example ui_fixtures > apps/desktop/ui/src/app/data/catalog.generated.ts`
//!
//! Also renders one sample "não consegui" report from fixed example data (no real probe runs).

use std::collections::BTreeMap;
use std::fmt::Write as _;

use hmd_core::report::{ReportInput, SystemSummary, render};
use hmd_core::{DiagnoseOptions, LOCALE, confidence_phrase, diagnose_with};
use hmd_domain::{ProblemFamily, ReportTrigger};
use hmd_policy::{CapabilityKind, Confidence, Platform};
use hmd_probes::{Finding, ProbeOutput, Severity};

/// A JSON/TypeScript string literal.
fn lit(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => {
                let _ = write!(out, "\\u{:04x}", c as u32);
            }
            // Line/paragraph separators are not valid in older JS string literals.
            '\u{2028}' => out.push_str("\\u2028"),
            '\u{2029}' => out.push_str("\\u2029"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn opt(s: Option<&str>) -> String {
    s.map_or_else(|| "null".to_string(), lit)
}

fn confidence_code(c: Confidence) -> &'static str {
    match c {
        Confidence::Unsure => "unsure",
        Confidence::Probable => "probable",
        Confidence::AlmostCertain => "almost_certain",
    }
}

fn main() {
    let catalog = match hmd_catalog::embedded() {
        Ok(c) => c,
        Err(errors) => {
            eprintln!("invalid catalog: {} error(s)", errors.len());
            std::process::exit(2);
        }
    };
    let mut s = String::new();
    let _ = writeln!(
        s,
        "// GENERATED by `cargo run -q -p hmd-core --example ui_fixtures`. Do not edit by hand.\n\
         // Source: catalog/ (version {}). SPDX-License-Identifier: GPL-3.0-or-later\n",
        catalog.version
    );
    let _ = writeln!(
        s,
        "export const CATALOG_VERSION = {};\n",
        lit(&catalog.version)
    );

    let _ = writeln!(s, "export const CONFIDENCE_PHRASES = {{");
    for c in [
        Confidence::AlmostCertain,
        Confidence::Probable,
        Confidence::Unsure,
    ] {
        let _ = writeln!(
            s,
            "  {}: {},",
            confidence_code(c),
            lit(confidence_phrase(c))
        );
    }
    let _ = writeln!(s, "}} as const;\n");

    let _ = writeln!(s, "export const FAMILIES = [");
    for family in ProblemFamily::ALL {
        let Some(pb) = catalog.playbook_for(family) else {
            continue;
        };
        let title = pb.title.get(LOCALE).map_or("", String::as_str);
        let _ = writeln!(s, "  {{");
        let _ = writeln!(s, "    code: {},", lit(family.code()));
        let _ = writeln!(s, "    title: {},", lit(title));
        let _ = writeln!(
            s,
            "    playbook: {},",
            lit(&format!("{}@{}", pb.id, pb.version))
        );
        let _ = writeln!(
            s,
            "    probes: [{}],",
            pb.probes
                .iter()
                .map(|p| lit(p))
                .collect::<Vec<_>>()
                .join(", ")
        );
        let _ = writeln!(s, "    diagnoses: [");
        for d in pb.diagnoses.iter().chain(std::iter::once(&pb.fallback)) {
            let Some(copy) = d.copy.get(LOCALE) else {
                continue;
            };
            let _ = writeln!(s, "      {{");
            let _ = writeln!(s, "        id: {},", lit(&d.id));
            let _ = writeln!(
                s,
                "        confidence: {},",
                lit(confidence_code(d.confidence))
            );
            let _ = writeln!(s, "        title: {},", lit(&copy.title));
            let _ = writeln!(s, "        explanation: {},", lit(&copy.explanation));
            let _ = writeln!(
                s,
                "        steps: [{}],",
                copy.steps
                    .iter()
                    .map(|x| lit(x))
                    .collect::<Vec<_>>()
                    .join(", ")
            );
            let _ = writeln!(
                s,
                "        fixes: [{}],",
                d.fixes
                    .iter()
                    .map(|x| lit(x))
                    .collect::<Vec<_>>()
                    .join(", ")
            );
            let _ = writeln!(s, "        report: {},", opt(d.report.map(|r| r.code())));
            let _ = writeln!(s, "      }},");
        }
        let _ = writeln!(s, "    ],");
        let _ = writeln!(s, "  }},");
    }
    let _ = writeln!(s, "] as const;\n");

    let _ = writeln!(s, "export const PROBES = [");
    for cap in catalog
        .catalog
        .iter()
        .filter(|c| c.kind == CapabilityKind::Probe)
    {
        let Some(copy) = catalog.meta.get(&cap.id).and_then(|m| m.copy.get(LOCALE)) else {
            continue;
        };
        let platforms: Vec<String> = cap
            .variants
            .keys()
            .map(|p| {
                lit(match p {
                    Platform::Windows => "windows",
                    Platform::Linux => "linux",
                })
            })
            .collect();
        let consent = cap
            .variants
            .values()
            .find_map(|v| v.consent_category.as_deref());
        let _ = writeln!(
            s,
            "  {{ id: {}, title: {}, looksAt: {}, never: {}, platforms: [{}], consent: {} }},",
            lit(&cap.id),
            lit(&copy.title),
            opt(copy.looks_at.as_deref()),
            opt(copy.never.as_deref()),
            platforms.join(", "),
            opt(consent)
        );
    }
    let _ = writeln!(s, "] as const;\n");

    let _ = writeln!(s, "export const FIXES = [");
    for cap in catalog
        .catalog
        .iter()
        .filter(|c| c.kind == CapabilityKind::Fix)
    {
        let Some(copy) = catalog.meta.get(&cap.id).and_then(|m| m.copy.get(LOCALE)) else {
            continue;
        };
        let elevation = cap.variants.values().any(|v| v.requires_elevation);
        let _ = writeln!(
            s,
            "  {{ id: {}, title: {}, risk: {}, undo: {}, requiresElevation: {elevation} }},",
            lit(&cap.id),
            lit(&copy.title),
            opt(copy.risk.as_deref()),
            opt(copy.undo.as_deref())
        );
    }
    let _ = writeln!(s, "] as const;\n");

    let _ = writeln!(s, "export const CONSENTS = [");
    for (id, notice) in &catalog.consents {
        let Some(copy) = notice.copy.get(LOCALE) else {
            continue;
        };
        let _ = writeln!(
            s,
            "  {{ id: {}, version: {}, title: {}, text: {} }},",
            lit(id),
            lit(&notice.version),
            lit(&copy.title),
            lit(&copy.text)
        );
    }
    let _ = writeln!(s, "] as const;\n");

    // Sample report from fixed example data: DNS failing, gateway fine.
    let fake = |id: &str| {
        let findings = if id == "net.dns.resolve" {
            vec![Finding {
                code: "net.dns.resolution_failing",
                severity: Severity::Critical,
            }]
        } else {
            vec![]
        };
        Ok(ProbeOutput {
            probe_id: "example",
            findings,
            evidence: BTreeMap::new(),
        })
    };
    let opts = DiagnoseOptions {
        platform: Platform::Windows,
        ..DiagnoseOptions::default()
    };
    if let Ok(d) = diagnose_with(catalog, ProblemFamily::Connectivity, &opts, fake) {
        let system = SystemSummary {
            os_name: Some("Windows".into()),
            os_version: Some("11 (exemplo)".into()),
            kernel_version: None,
            arch: Some("x86_64".into()),
        };
        let text = render(&ReportInput {
            catalog,
            diagnosis: &d,
            trigger: ReportTrigger::PersonRequested,
            symptom: Some("A internet parou de abrir os sites desde ontem à noite."),
            system: Some(&system),
            created_at: 1_760_400_000,
        });
        let _ = writeln!(
            s,
            "/** Example report rendered by the real `report@1` renderer from fixed data. */"
        );
        let _ = writeln!(s, "export const SAMPLE_REPORT = {};", lit(&text));
    }
    print!("{s}");
}
